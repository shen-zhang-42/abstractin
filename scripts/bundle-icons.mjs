// Bundle SVG text with the plugin so native windows and reader frames do not
// need separate resource reads for every button. Original files retain credits.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const code = readFileSync(new URL('src/content/zusia.js', root), 'utf8');
const mapping = code.match(/\tICON_FILES: \{([\s\S]*?)\n\t\},/)[1];
const files = [...new Set([...mapping.matchAll(/^\s*(?:"[^"]+"|\w+):\s*"([^"]+\.svg)",?\s*$/gm)].map(match => match[1]))].sort();
const icons = Object.fromEntries(files.map(file => [file, readFileSync(new URL('src/content/icons/' + file, root), 'utf8').trim()]));
const source = '// Generated by scripts/bundle-icons.mjs. See THIRD_PARTY_NOTICES.md.\n"use strict";\nObject.assign(Zusia, { BUNDLED_ICONS: ' + JSON.stringify(icons, null, '\t') + ' });\n';
writeFileSync(new URL('src/content/icon-assets.js', root), source);
console.log('Bundled ' + files.length + ' SVG icons');
