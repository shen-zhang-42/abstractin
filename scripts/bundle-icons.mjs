// Bundle SVG text with the plugin so native windows and reader frames do not
// need separate resource reads for every button. Original files retain credits.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const code = readFileSync(new URL('src/content/abstractin.js', root), 'utf8');
const mapping = code.match(/\tICON_FILES: \{([\s\S]*?)\n\t\},/)[1];
const files = [...new Set([...mapping.matchAll(/^\s*(?:"[^"]+"|\w+):\s*"([^"]+\.svg)",?\s*$/gm)].map(match => match[1]))].sort();
const icons = Object.fromEntries(files.map(file => [file, readFileSync(new URL('src/content/icons/' + file, root), 'utf8').replace(/\r\n/g, '\n').trim()]));
const source = '// Generated by scripts/bundle-icons.mjs. See THIRD_PARTY_NOTICES.md.\n"use strict";\nObject.assign(AbstractIn, { BUNDLED_ICONS: ' + JSON.stringify(icons, null, '\t') + ' });\n';
writeFileSync(new URL('src/content/icon-assets.js', root), source);
// Preferences and toolbar surfaces share one original brand drawing.
for (const size of [16, 20]) writeFileSync(new URL(`src/icons/icon${size}.svg`, root), icons['abstractin-mark.svg'].replace('<svg ', `<svg width="${size}" height="${size}" `) + '\n');
console.log('Bundled ' + files.length + ' SVG icons');
